"""Model-library startup path and read-only diagnostics; no TensorFlow or DNNDK."""
from __future__ import print_function
import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parents[1]
BOOTSTRAP_KEY = 'MOBILEVIT_MV2_LIBRARY_BOOTSTRAP'


def ensure_library_search_path(config_path):
    """Re-exec once so Linux's loader sees the model directory at startup."""
    if not sys.platform.startswith('linux'):
        return
    directory = str(Path(config_path).resolve().parent / 'model')
    previous = os.environ.get('LD_LIBRARY_PATH', '')
    if previous.split(':', 1)[0] == directory:
        return
    if os.environ.get(BOOTSTRAP_KEY) == directory:
        raise RuntimeError('Model library path was not retained at process startup. '
                           'Set LD_LIBRARY_PATH to {} before starting Python.'.format(directory))
    environment = os.environ.copy()
    environment['LD_LIBRARY_PATH'] = directory + (':' + previous if previous else '')
    environment[BOOTSTRAP_KEY] = directory
    print('[startup] Adding model library directory: ' + directory, file=sys.stderr, flush=True)
    os.execve(sys.executable, [sys.executable] + sys.argv, environment)


def elf_kernel_names(raw):
    if len(raw) < 64 or raw[:6] != b'\x7fELF\x02\x01':
        raise ValueError('Not a little-endian ELF64 shared library')
    kind, machine = struct.unpack_from('<HH', raw, 16)
    if (kind, machine) != (3, 183):
        raise ValueError('Expected AArch64 shared library; ELF type={}, machine={}'.format(kind, machine))
    offset = struct.unpack_from('<Q', raw, 40)[0]
    size, count, strings = struct.unpack_from('<HHH', raw, 58)
    if size < 64 or not 0 <= strings < count or offset + size * count > len(raw):
        raise ValueError('Invalid ELF section table')
    entries = [struct.unpack_from('<IIQQQQIIQQ', raw, offset + i * size) for i in range(count)]
    table = entries[strings]
    if table[4] + table[5] > len(raw):
        raise ValueError('Invalid ELF section-name table')
    names = raw[table[4]:table[4] + table[5]]
    prefix = '.deephi.metadata.'
    kernels = []
    for entry in entries:
        name = names[entry[0]:].split(b'\0', 1)[0].decode('ascii')
        if name.startswith(prefix):
            kernels.append(name[len(prefix):])
    if not kernels:
        raise ValueError('No .deephi.metadata.* DPU kernel sections')
    return sorted(kernels)


def inspect_libraries(config_path, mv2_backend='dpu', load=False):
    root = Path(config_path).resolve().parent
    config = json.loads(Path(config_path).read_text(encoding='utf-8'))
    stages = [('front', config['front'])] + [(s['name'], s) for s in config['stages']
        if s['backend'] == 'dpu' and mv2_backend == 'dpu']
    records, handles = [], []
    for name, stage in stages:
        path = root / 'model' / ('libdpumodel' + stage['kernel'] + '.so')
        if not path.is_file():
            for cand in (root / 'model').glob('*.so'):
                try:
                    if stage['kernel'] in elf_kernel_names(cand.read_bytes()):
                        path = cand
                        break
                except Exception:
                    pass
        record = {'stage': name, 'kernel': stage['kernel'], 'path': str(path), 'passed': False}
        try:
            if not path.is_file():
                raise ValueError('SO is missing. Finish Docker compile/link steps 5/6 and copy model/ to the board.')
            raw = path.read_bytes()
            kernels = elf_kernel_names(raw)
            record['embedded_kernels'] = kernels
            if stage['kernel'] not in kernels:
                raise ValueError('Configured kernel name does not match the kernel embedded in this SO')
            missing = [key for key in ('input_node', 'output_node', 'so_sha256') if not stage.get(key)]
            if missing:
                raise ValueError('Missing {}. Copy the runtime_config.json generated by Docker step 6.'.format(', '.join(missing)))
            if hashlib.sha256(raw).hexdigest() != stage['so_sha256']:
                raise ValueError('SO hash differs from runtime_config.json; copy the matching build together')
            if load:
                # Absolute path exposes the actual loader/dependency error without calling N2Cube.
                handles.append(ctypes.CDLL(str(path), mode=getattr(ctypes, 'RTLD_GLOBAL', 0)))
                record['absolute_path_load'] = 'ok'
            record['passed'] = True
        except (ValueError, OSError, UnicodeError, struct.error) as error:
            record['error'] = str(error)
        records.append(record)
    return {'passed': all(r['passed'] for r in records), 'libraries': records,
            'LD_LIBRARY_PATH': os.environ.get('LD_LIBRARY_PATH', ''),
            'scope': 'Library files, embedded kernel names, metadata and optional loader check; no DPU task is run'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=HERE / 'runtime_config.json')
    parser.add_argument('--mv2-backend', choices=('dpu', 'numpy'), default='dpu')
    parser.add_argument('--load', action='store_true', help='On the board, also load SOs to report dependency errors')
    args = parser.parse_args()
    if args.load:
        ensure_library_search_path(args.config)
    report = inspect_libraries(args.config, args.mv2_backend, args.load)
    print(json.dumps(report, indent=2))
    if not report['passed']:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
